export const ALL_CATEGORIES = Object.keys(CATEGORY_KEYWORDS)

// 最长关键词优先匹配；未命中返回 null
export function matchCategory(userInput) {
  if (!userInput) return null
  const input = String(userInput).toLowerCase().trim()
  let best = null
  let bestLen = 0
  for (const [category, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
    for (const keyword of keywords) {
      const kw = keyword.toLowerCase()
      if (input.includes(kw) && kw.length > bestLen) {
        best = category
        bestLen = kw.length
      }
    }
  }
  return best
}

// 推荐相近分类（1~3 个，按相关度降序，仅强相关不强凑；完全无关联时兜底 topN 个）
export function suggestCategories(userInput, topN = 3) {
  if (!userInput) return []
  const inputLower = String(userInput).toLowerCase().trim()
  const inputChars = new Set(inputLower)
  const scores = {}
  for (const [category, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
    const relatedWords = [category.toLowerCase(), ...keywords.map((k) => k.toLowerCase())]
    let hitScore = 0
    let charOverlap = 0
    for (const word of relatedWords) {
      if (word && inputLower.includes(word)) hitScore += 5 + word.length
      if (word) {
        for (const ch of new Set(word)) if (inputChars.has(ch)) charOverlap++
      }
    }
    scores[category] = hitScore + charOverlap
  }
  const ranked = Object.entries(scores).sort((a, b) => b[1] - a[1])
  const strong = ranked.filter(([, s]) => s > 0).slice(0, topN).map(([c]) => c)
  return strong.length ? strong : ranked.slice(0, topN).map(([c]) => c)
}
